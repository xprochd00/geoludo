// Converts data/history-questions.json (the editable source) into data/history.js, which the game
// loads with a plain <script> tag so it also works when index.html is opened straight from disk.
// Usage: node tools/build-history.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
global.window = {};
require(path.join(root, 'data/world.js'));
const byIso2 = new Map(window.WORLD.countries.filter(c => c.iso2).map(c => [c.iso2, c]));
const src = JSON.parse(fs.readFileSync(path.join(root, 'data/history-questions.json'), 'utf8'));
const out = [];
for (const q of src) {
  const c = byIso2.get(q.answer.iso2);
  if (!c) throw new Error(`${q.id}: no playable country with ISO code ${q.answer.iso2}`);
  if (!(q.difficulty >= 1 && q.difficulty <= 6)) throw new Error(`${q.id}: difficulty must be 1-6`);
  const rec = { id: q.id, lvl: q.difficulty, cat: q.category, q: q.question, a: c.id };
  if (q.time_sensitive) rec.ts = 1;
  if (q.contested_territory) rec.ct = 1;
  out.push(rec);
}
fs.writeFileSync(path.join(root, 'data/history.js'),
  '// Generated by tools/build-history.js from data/history-questions.json. Do not edit.\nwindow.HISTORY_QUESTIONS = ' + JSON.stringify(out) + ';\n');
console.log('history questions:', out.length, 'per level:', [1, 2, 3, 4, 5, 6].map(l => out.filter(q => q.lvl === l).length).join(' '));
