// Generates data/timetravel.js from data/timetravel-questions.json (Geo Time Travel's own question pool).
// Usage: node tools/build-timetravel.js   (needs data/world.js for the ISO codes)
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
global.window = {};
require(path.join(ROOT, 'data/world.js'));
const byIso2 = new Map(window.WORLD.countries.filter((c) => c.iso2 && c.fame).map((c) => [c.iso2, c]));
const ERAS = ['prehistory', 'ancient', 'middle_ages', 'early_modern', 'modern'];
const src = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/timetravel-questions.json'), 'utf8'));
const ids = new Set();
const texts = new Set();
const out = src.map((q) => {
  if (ids.has(q.id)) throw new Error(`duplicate id ${q.id}`);
  ids.add(q.id);
  const t = q.question.trim().toLowerCase();
  if (texts.has(t)) throw new Error(`duplicate question ${q.id}`);
  texts.add(t);
  const era = ERAS.indexOf(q.period);
  if (era < 0) throw new Error(`${q.id}: unknown period ${q.period}`);
  const c = byIso2.get(q.answer.iso2);
  if (!c) throw new Error(`${q.id}: ${q.answer.iso2} is not a playable country`);
  return { id: q.id, era, q: q.question.trim(), a: c.id };
});
fs.writeFileSync(path.join(ROOT, 'data/timetravel.js'), `// Generated by tools/build-timetravel.js from data/timetravel-questions.json. Do not edit.\nwindow.TIME_TRAVEL_QUESTIONS = ${JSON.stringify(out)};\n`);
console.log('time travel questions', out.length, 'per era', ERAS.map((e, i) => `${e} ${out.filter((q) => q.era === i).length}`).join(', '));
